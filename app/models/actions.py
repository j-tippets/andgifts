from datetime import date, datetime, timedelta
from app.extensions import db
from app.models.org import gen_uuid

# How many days past target_date a pending suggestion is allowed to sit
# before the nightly job auto-expires it (see expire_stale_suggestions in
# app/services/suggestion_engine.py). Hardcoded for now rather than a
# per-org setting -- easy to promote later if agencies want it tuned.
EXPIRATION_GRACE_DAYS = 10

# What the agent is charged for a handwritten note, same "charge the
# agent's saved card at approval time" model as a gift (see
# dashboard.approve_action) -- covers the card/writing/postage plus a
# bit of margin. Flat rate for now rather than a catalog item, since
# there's no product/size variation the way there is for gifts.
HANDWRITTEN_NOTE_PRICE_CENTS = 500

# action_type values that mean a real Stripe charge happens at approval
# time (see dashboard.approve_action's _charge_for_approval). Single
# source of truth for anywhere that needs to treat these differently
# from a non-paid action (email, text) -- e.g. dashboard.unapprove_action
# refuses to undo one of these, since doing so would discard the only
# record of a completed financial transaction and reopen the door to a
# duplicate charge on re-approval, with no refund/cancellation flow yet
# to actually reverse what already happened.
PAID_ACTION_TYPES = ("gift", "handwritten_note")


class SuggestedAction(db.Model):
    """
    A single card on the agent's daily dashboard: 'reach out to X because Y,
    here's a suggested gift/email/text'. Generated by the nightly job,
    approved/edited/skipped by the agent.
    """
    __tablename__ = "suggested_actions"

    __table_args__ = (
        # Backstop for _campaign_suggestion_exists in suggestion_engine.py,
        # which is a check-then-insert with no transactional guarantee: two
        # near-simultaneous runs of generate_campaign_suggestions_for_org
        # for the same org (two gunicorn workers, or the nightly job
        # overlapping an on-demand dashboard-triggered run) can both pass
        # the "does this already exist" check before either commits, and
        # both create a suggestion -- observed in practice as a paused-
        # then-resumed flow producing two suggestions for the same
        # occurrence, each with its own independently-generated LLM
        # reasoning text. MySQL treats each NULL as distinct in a unique
        # index, so this only actually constrains campaign-sourced rows
        # (source_campaign_id and triggering_event_id both set) -- the
        # older non-campaign GiftTrigger path (both NULL there) is
        # untouched, and dedup logic for it lives elsewhere (see
        # expire_stale_suggestions's docstring). See suggestion_engine.py's
        # generate_campaign_suggestions_for_org for the matching
        # savepoint + IntegrityError handling this relies on.
        db.UniqueConstraint(
            "org_id", "source_campaign_id", "contact_id", "triggering_event_id", "target_date",
            name="uq_suggested_action_campaign_occurrence",
        ),
    )

    # Lets dashboard/index.html's merged card stack (suggestions +
    # FlowRecommendation, sorted together by created_at) branch on type
    # without checking __class__ in the template.
    item_kind = "suggestion"

    id = db.Column(db.String(36), primary_key=True, default=gen_uuid)
    org_id = db.Column(db.String(36), db.ForeignKey("orgs.id"), nullable=False, index=True)
    contact_id = db.Column(db.String(36), db.ForeignKey("contacts.id"), nullable=False, index=True)
    triggering_event_id = db.Column(db.String(36), db.ForeignKey("timeline_events.id"), nullable=True)
    # Set when this suggestion came from the campaign engine (stage 3);
    # NULL for suggestions generated by the older GiftTrigger path.
    source_campaign_id = db.Column(db.String(36), db.ForeignKey("campaigns.id"), nullable=True, index=True)

    action_type = db.Column(
        db.Enum("gift", "email", "text", "handwritten_note", name="suggested_action_type"), nullable=False
    )
    suggested_gift_id = db.Column(db.String(36), db.ForeignKey("gift_catalog_items.id"), nullable=True)

    reason_text = db.Column(db.Text, nullable=False)  # the human-readable "why", LLM or template generated
    # The actual customer-facing copy for email/text/handwritten_note actions
    # (LLM-written or template-rendered). NULL for gift-only actions and for
    # older GiftTrigger-generated suggestions that predate this field.
    generated_message = db.Column(db.Text, nullable=True)
    target_date = db.Column(db.Date, nullable=False)  # the date of the event this relates to

    # "processing" is a brief, transitional claim state -- see
    # dashboard.approve_action's _claim_action_for_processing: a gift or
    # handwritten_note approval atomically flips pending -> processing
    # before charging the card, so a double-click, a retried request, or
    # two browser tabs can't both pass a plain status check and both
    # charge. Reverts to "pending" if the charge fails, or moves on to
    # "approved" once it succeeds -- a row should never be visibly stuck
    # here outside of that brief window, and
    # jobs/reconcile_stuck_processing_actions.py is the backstop for the
    # rare case where a process crash mid-charge leaves one stranded
    # anyway (see processing_started_at below).
    status = db.Column(
        db.Enum(
            "pending", "processing", "approved", "skipped", "sent", "deleted", "expired",
            name="suggested_action_status",
        ),
        default="pending",
        index=True,
    )
    # When the current "processing" claim was taken (see
    # dashboard._claim_action_for_processing) -- NULL outside of that
    # window. Exists so jobs/reconcile_stuck_processing_actions.py can
    # tell a normal, currently-in-flight claim (a few hundred ms to a
    # couple seconds, waiting on Stripe) apart from one that's actually
    # stuck (the process that held it crashed -- OOM kill, a deploy
    # restart mid-request -- before it could release the claim or
    # finish approving). Cleared (set back to NULL) whenever a row
    # leaves "processing" by any path, so a stale value never lingers
    # on a row that's since moved on.

    created_at = db.Column(db.DateTime, default=datetime.utcnow)
    resolved_at = db.Column(db.DateTime, nullable=True)  # when approved/skipped
    processing_started_at = db.Column(db.DateTime, nullable=True)

    contact = db.relationship("Contact")
    triggering_event = db.relationship("TimelineEvent")
    suggested_gift = db.relationship("GiftCatalogItem")
    source_campaign = db.relationship("Campaign")

    @property
    def owning_agent(self):
        """Best guess at which agent this suggestion 'belongs to', for the
        actions report and its per-agent filter: the flow's owner if it
        came from a personal flow, else whoever privately owns the
        contact. None for a shared contact with no owning flow -- those
        are org-wide/legacy and aren't any one agent's."""
        if self.source_campaign_id:
            return self.source_campaign.owner if self.source_campaign else None
        return self.contact.owner if self.contact else None

    @staticmethod
    def visible_to(query, user):
        """Scope a SuggestedAction query to what `user` is allowed to see
        on their Today dashboard: admins see every pending suggestion in
        the org; agents see only ones with no specific owning agent (a
        shared contact, or a team-wide flow -- see owning_agent) plus
        their own. Mirrors Contact.visible_to's shared-vs-private split,
        just computed from owning_agent instead of a single column since
        a suggestion's owner can come from either the contact or the
        triggering flow."""
        if user.is_admin:
            return query
        from app.models.contact import Contact
        from app.models.campaigns import Campaign
        return (
            query
            .outerjoin(Contact, SuggestedAction.contact_id == Contact.id)
            .outerjoin(Campaign, SuggestedAction.source_campaign_id == Campaign.id)
            .filter(db.or_(
                db.and_(
                    SuggestedAction.source_campaign_id.is_(None),
                    db.or_(Contact.owner_user_id.is_(None), Contact.owner_user_id == user.id),
                ),
                db.and_(
                    SuggestedAction.source_campaign_id.isnot(None),
                    db.or_(Campaign.owner_user_id.is_(None), Campaign.owner_user_id == user.id),
                ),
            ))
        )

    @staticmethod
    def owned_by(query, agent_id):
        """Scope a SuggestedAction query to suggestions specifically owned
        by one agent (see owning_agent) -- used by the admin dashboard's
        per-agent filter dropdown. Unlike visible_to, this excludes
        shared/team-wide items with no specific owner, since the admin
        asked to see one agent's queue specifically, not everything that
        agent happens to be allowed to see."""
        from app.models.contact import Contact
        from app.models.campaigns import Campaign
        return (
            query
            .outerjoin(Contact, SuggestedAction.contact_id == Contact.id)
            .outerjoin(Campaign, SuggestedAction.source_campaign_id == Campaign.id)
            .filter(db.or_(
                db.and_(SuggestedAction.source_campaign_id.is_(None), Contact.owner_user_id == agent_id),
                db.and_(SuggestedAction.source_campaign_id.isnot(None), Campaign.owner_user_id == agent_id),
            ))
        )

    @property
    def readiness_blocked_reason(self):
        """None if this action can actually be carried out as-is;
        otherwise a short, agent-facing reason it can't be -- checked
        both to disable Approve on the dashboard card (so the agent
        isn't surprised by a failure after already committing to
        approve, especially since the swipe gesture approves via a
        background fetch() and wouldn't visibly surface a failure on
        the current page at all) and again server-side in
        approve_action itself as the actual enforcement; the card-side
        check is UX only and isn't trusted on its own."""
        if self.action_type == "email" and not self.contact.primary_email():
            return "This contact doesn't have an email address on file yet."
        if self.action_type in ("gift", "handwritten_note") and not self.contact.has_shipping_address:
            return "This contact doesn't have a shipping address on file yet."
        return None

    @property
    def expires_on(self):
        """The date after which, if still pending, the nightly job will
        auto-expire this suggestion (see expire_stale_suggestions in
        app/services/suggestion_engine.py). Shown on the dashboard card so
        the agent knows there's a clock on it -- not just informational
        after the fact."""
        return self.target_date + timedelta(days=EXPIRATION_GRACE_DAYS)

    @property
    def gift_timing(self):
        """For a gift suggestion with a resolved catalog item, how much
        runway is left to approve it and still have it ship in time for
        target_date -- based on the gift's lead_time_days (order-to-ship,
        not a delivery promise; we don't control carrier transit time).

        Returns None for non-gift actions or a gift with no catalog item
        resolved yet (nothing to compute a lead time from). Otherwise a
        dict: {order_by, days_left, urgency}, where urgency is one of:
          - "late": order_by has already passed and this is still pending
          - "urgent": needs to be approved today (0 days left)
          - "soon": 1-2 days left
          - "ok": 3+ days left
        """
        if self.action_type != "gift" or not self.suggested_gift:
            return None

        order_by = self.target_date - timedelta(days=self.suggested_gift.lead_time_days)
        days_left = (order_by - date.today()).days

        if days_left < 0:
            urgency = "late"
        elif days_left == 0:
            urgency = "urgent"
        elif days_left <= 2:
            urgency = "soon"
        else:
            urgency = "ok"

        return {"order_by": order_by, "days_left": days_left, "urgency": urgency}



class ActionLog(db.Model):
    """
    Permanent record of what was actually sent -- for agent history,
    spend tracking / tax export, and to avoid duplicate suggestions.
    """
    __tablename__ = "action_log"

    id = db.Column(db.String(36), primary_key=True, default=gen_uuid)
    org_id = db.Column(db.String(36), db.ForeignKey("orgs.id"), nullable=False, index=True)
    contact_id = db.Column(db.String(36), db.ForeignKey("contacts.id"), nullable=False, index=True)
    suggested_action_id = db.Column(db.String(36), db.ForeignKey("suggested_actions.id"), nullable=True)

    action_type = db.Column(db.Enum("gift", "email", "text", "handwritten_note", name="action_log_type"), nullable=False)
    detail = db.Column(db.Text, nullable=True)  # e.g. gift name + price, or email subject line
    cost_cents = db.Column(db.Integer, nullable=True)  # for spend tracking / tax export

    # Automated-send tracking. NULL for action types that aren't wired up to
    # an actual send yet (gift fulfillment, text, handwritten_note) -- those
    # stay manual for now, so this column simply doesn't apply to them.
    # "email" is the first channel with a real send behind it (SendGrid);
    # 'sent' / 'failed' record whether that actually went out, with the
    # reason in delivery_error when it didn't.
    delivery_status = db.Column(db.Enum("sent", "failed", "blocked", name="action_log_delivery_status"), nullable=True)
    delivery_error = db.Column(db.Text, nullable=True)

    # Set when this is a gift action that actually charged a saved card
    # (see services.payments.charge_saved_card) -- automated flow
    # approvals only reach this ActionLog-creation step at all once the
    # charge has already succeeded (a decline blocks the approval
    # entirely and leaves the suggestion pending, so no ActionLog row
    # is ever created for a failed charge). NULL for manual one-off
    # orders (those get their own Order row instead) and for action
    # types that don't involve payment.
    stripe_payment_intent_id = db.Column(db.String(255), nullable=True)

    # Which agent actually approved this -- used for the "who did what"
    # column/filter on the org-wide actions report. Nullable because it's
    # only set going forward (backfilled from ContactAuditLog for existing
    # rows where that history exists); a NULL here just means "unknown",
    # not "nobody".
    approved_by_user_id = db.Column(db.String(36), db.ForeignKey("users.id"), nullable=True, index=True)

    sent_at = db.Column(db.DateTime, default=datetime.utcnow)

    contact = db.relationship("Contact")
    suggested_action = db.relationship("SuggestedAction")
    approved_by = db.relationship("User", foreign_keys=[approved_by_user_id])

    @property
    def owning_agent(self):
        """Who to credit this completed action to: whoever actually
        approved it if we know that, else fall back to the suggestion's
        owning agent (covers old rows from before approved_by_user_id
        existed, in the rare case the backfill didn't find a match)."""
        if self.approved_by_user_id:
            return self.approved_by
        return self.suggested_action.owning_agent if self.suggested_action else None


class FlowRecommendation(db.Model):
    """
    A single 'you might want a flow for this' card on the agent's Today
    dashboard -- distinct from SuggestedAction (which is 'reach out to
    this contact'). Generated by
    services.flow_recommendations.generate_flow_recommendations_for_user,
    which looks for a milestone type showing up on several of the
    agent's own contacts with no active personal Campaign covering it --
    a coverage gap, not a per-contact trigger.

    One row per (user, event_type), enforced below, and never
    regenerated once it exists regardless of status -- accepting or
    dismissing a recommendation is a one-way door for that gap; if the
    agent later builds an unrelated flow for the same event_type
    themselves (not via this card), the row is just left dangling in
    whatever status it was in rather than cleaned up, since it's no
    longer shown either way (see the dashboard route's pending-only
    filter) and isn't worth extra bookkeeping to delete.
    """
    __tablename__ = "flow_recommendations"
    __table_args__ = (
        db.UniqueConstraint("user_id", "event_type", name="uq_flow_recommendation_user_event"),
    )

    # See SuggestedAction.item_kind's comment -- same purpose.
    item_kind = "recommendation"

    id = db.Column(db.String(36), primary_key=True, default=gen_uuid)
    org_id = db.Column(db.String(36), db.ForeignKey("orgs.id"), nullable=False, index=True)
    user_id = db.Column(db.String(36), db.ForeignKey("users.id"), nullable=False, index=True)

    event_type = db.Column(db.String(50), nullable=False)
    # Snapshot of CustomEventType.label at generation time (same
    # convention as ContactAuditLog.contact_name_snapshot) -- avoids a
    # join on every dashboard load, and a milestone getting renamed
    # later shouldn't retroactively change what an already-shown
    # recommendation says.
    event_label = db.Column(db.String(100), nullable=False)
    # How many of the agent's own visible contacts have this milestone
    # logged, at generation time -- also a snapshot, not a live count.
    contact_count = db.Column(db.Integer, nullable=False)

    status = db.Column(
        db.Enum("pending", "accepted", "dismissed", name="flow_recommendation_status"),
        default="pending",
        nullable=False,
        index=True,
    )

    created_at = db.Column(db.DateTime, default=datetime.utcnow)
    resolved_at = db.Column(db.DateTime, nullable=True)  # when accepted/dismissed

    org = db.relationship("Org")
    user = db.relationship("User")


class FillerActionState(db.Model):
    """
    Per-user resolution state for a synthetic "filler" Today-tab card --
    see app/services/filler_actions.py for the actual card definitions
    and generation logic.

    Unlike SuggestedAction/FlowRecommendation, filler cards aren't
    generated ahead of time and stored; they're computed fresh on every
    dashboard load from static rules plus live data (no contacts yet, no
    payment method on file, etc.). This table only exists to remember
    which ones a user has already resolved (accepted/"actioned" or
    dismissed), so a resolved one never reappears -- same one-way-door
    convention as FlowRecommendation.

    filler_key is a stable string id from the registry (e.g.
    "FILL-ACC-01"), suffixed with a contact id for the per-contact
    fillers (e.g. "FILL-CON-03:<contact_id>") so each qualifying contact
    is resolved independently rather than one dismissal hiding the
    filler for every contact that would otherwise qualify.
    """
    __tablename__ = "filler_action_states"
    __table_args__ = (
        db.UniqueConstraint("user_id", "filler_key", name="uq_filler_action_user_key"),
    )

    # See SuggestedAction.item_kind's comment -- same purpose, though
    # filler cards are never actually stored/queried as this model on
    # the dashboard itself (see generate_filler_cards) -- only their
    # resolution state is.
    item_kind = "filler"

    id = db.Column(db.String(36), primary_key=True, default=gen_uuid)
    org_id = db.Column(db.String(36), db.ForeignKey("orgs.id"), nullable=False, index=True)
    user_id = db.Column(db.String(36), db.ForeignKey("users.id"), nullable=False, index=True)
    filler_key = db.Column(db.String(120), nullable=False, index=True)

    status = db.Column(db.Enum("dismissed", "actioned", name="filler_action_status"), nullable=False)

    created_at = db.Column(db.DateTime, default=datetime.utcnow)
    resolved_at = db.Column(db.DateTime, default=datetime.utcnow)

    org = db.relationship("Org")
    user = db.relationship("User")
