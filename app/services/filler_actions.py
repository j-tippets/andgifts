_REGISTRY_BY_KEY = {d.key: d for d in REGISTRY}


def generate_filler_cards(user, limit):
    """Return up to `limit` FillerCard objects for `user`'s Today tab, in
    tier order (account -> contact -> discovery), skipping anything
    already resolved (dismissed or actioned) for this user. `limit` is
    however many cards short of TARGET_CARD_COUNT the real queue
    (SuggestedAction + FlowRecommendation) already is -- filler only
    tops that up, it never displaces a real card."""
    if limit <= 0:
        return []

    resolved_keys = {
        row.filler_key for row in FillerActionState.query.filter_by(user_id=user.id).all()
    }

    cards = []
    for definition in sorted(REGISTRY, key=lambda d: d.tier):
        if len(cards) >= limit:
            break

        if definition.per_contact:
            shown = 0
            for contact in definition.contact_query(user):
                if len(cards) >= limit or shown >= MAX_PER_CONTACT_CARDS:
                    break
                key = f"{definition.key}:{contact.id}"
                if key in resolved_keys:
                    continue
                cards.append(FillerCard(
                    key=key,
                    tier=definition.tier,
                    title=definition.title.format(contact=contact.household_name),
                    reason_text=definition.reason_text,
                    cta_label=definition.cta_label,
                    cta_url=_build_url(definition, user, contact),
                    contact=contact,
                ))
                shown += 1
        else:
            if definition.key in resolved_keys:
                continue
            if not definition.condition(user):
                continue
            cards.append(FillerCard(
                key=definition.key,
                tier=definition.tier,
                title=definition.title,
                reason_text=definition.reason_text,
                cta_label=definition.cta_label,
                cta_url=_build_url(definition, user),
            ))

    return cards[:limit]


def resolve_target_url(user, filler_key):
    """Given a filler_key (possibly "<BASE_KEY>:<contact_id>" for a
    per-contact filler), return the URL its CTA button should go to.
    Doesn't re-check the underlying condition -- once an agent taps the
    card we send them to the CTA regardless of whether a fresh query
    would still technically match (e.g. someone else just added the
    missing shipping address a second ago)."""
    base_key, _, contact_id = filler_key.partition(":")
    definition = _REGISTRY_BY_KEY.get(base_key)
    if not definition:
        return None
    if contact_id:
        from app.models import Contact
        contact = Contact.query.get(contact_id)
        if not contact:
            return None
        return _build_url(definition, user, contact)
    return _build_url(definition, user)


def record_resolution(user, filler_key, status):
    """Marks a filler card resolved (dismissed or actioned) so it never
    reappears for this user. A no-op if it's somehow already resolved
    (e.g. a double form submit) -- the original record wins."""
    existing = FillerActionState.query.filter_by(user_id=user.id, filler_key=filler_key).first()
    if existing:
        return
    db.session.add(FillerActionState(
        org_id=user.org_id,
        user_id=user.id,
        filler_key=filler_key,
        status=status,
        resolved_at=datetime.utcnow(),
    ))
    db.session.commit()
